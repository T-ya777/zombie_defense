def game_getShortestPathMedium(app, path, visited, x, y, best):
    if best != None and len(path) > len(best):
        return None
        
    if x == 0 or x == app.rows - 1 or y == 0 or y == app.cols - 1:
        return path
        
    else:
        shortest = best
        visited.add((x, y))
        for dx, dy in [(-1, 0), (1, 0), (0, 1), (0, -1)]:
            row, col = x + dx, y + dy
            if (row, col) not in visited and isLegalMove(app, row, col):
                newpath = path + [(row, col)]
                solution = game_getShortestPathMedium(app, newpath, visited, row, col, shortest)
                if solution != None:
                    if shortest == None or len(solution) < len(shortest):
                        shortest = solution
        visited.remove((x, y))
        return shortest

