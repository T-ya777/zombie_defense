def play_onKeyHold(app, keys):
    if '1' in keys and '2' in keys and '5' in keys:
        app.specialMood = not app.specialMood
        print('specialMood:', app.specialMood)
    if not app.pause and not app.gameOver and app.bombState != 'aiming':
        if 'left' in keys and not app.reachLeftWall:
            for solider in app.solider:
                solider.x -= 5
                app.reachRightWall = False
                if solider.x - solider.r <= 0:
                    solider.x = solider.r
                    app.reachLeftWall = True
        if 'right' in keys and not app.reachRightWall:
            for solider in app.solider:
                solider.x += 5
                app.reachLeftWall = False
                if solider.x + solider.r >= app.width:
                    solider.x = app.width - solider.r
                    app.reachRightWall = True
                
def play_onKeyPress(app, key):
    if app.specialMood:
        if key == 'up' and len(app.solider) < 6:
            lastSolider  = app.solider[-1]
            firstSolider  = app.solider[0]
            if len(app.solider) == 3 or len(app.solider) == 7:
                x = firstSolider.x + firstSolider.r * 2
                y = firstSolider.y + firstSolider.r * 2
                r = lastSolider.r
            else:
                x = lastSolider.x - 4 * lastSolider.r
                y = lastSolider.y
                r = lastSolider.r
            app.solider.append(Solider(x, y, r))
        if key == 'down':
            if len(app.solider) > 1:
                app.solider.pop()
        if key == 'm':
            app.money += 5000
        if key == 'n':
            bonus = app.bonusItem[0]
            bonus.blood -= 100
        if key == '2':
            app.bonusItem.insert(1, BonusItem(150, 'box', 'doubleMoney'))
        if key == '3':
            app.bonusItem.insert(1, BonusItem(150, 'box', 'puzzle'))
        if key == '4':
            app.bonusItem.insert(1, BonusItem(150, 'ice', 'gun'))
        if key == 'a':
            app.ATK += 10
        if not app.pause and not app.gameOver:
            if key == 'g':
                app.gemInsideGame += 10
            if key == 'e':
                app.experience += 1000
          
def play_onStep(app):
    app.step += 1
    app.bulletTimer += 1
    
    play_checkGameOver(app)
    play_checkGameOverTimer(app)
    play_updateBullet(app)
    play_updateBonus(app)
    play_checkBonusState(app)
    play_checkEnemyAvaliability(app)
    play_showWarningMessage(app)
    play_showAwardMessage(app)
    if not app.pause and not app.gameOver and app.bombState != 'aiming':
        play_produceBullet(app)
        play_produceEnemy(app)
        play_bulletMove(app)
        play_enemyMove(app)
        play_checkBombExplode(app)
        play_checkExperience(app)
        play_checkMoneyBoostTimer(app)
        if app.step % 30 == 0:
            play_checkEnemyState(app)
            play_checkZombieAttack(app)
            if app.explodeTimer != None:
                app.explodeTimer -= 1
        if app.wallBeingAttacked and app.soundEffect:
            app.wallHit.play()

    if not app.pause and not app.gameOver and app.bombState == 'aiming':
        play_checkBombAimTimer(app)

def play_updateBonus(app):
    # learnt this way of weighted random from post 
    # https://stackoverflow.com/questions/14992521/python-weighted-random 
    if len(app.bonusItem) >= 4:
        return
    btypeList = ['ice'] * 30 + ['box'] * 70
    btype = random.choice(btypeList)
    if btype == 'ice':
        blood = random.choice(range(app.experienceLevel * 100, 
                                    app.experienceLevel * 1000, 100))
        if len(app.solider) < 7:
            award = random.choice(['solider', 'gun'])
        else:
            award = 'gun'
    else:
        blood = random.choice(range(max(app.experienceLevel * 50, 100), 
                                app.experienceLevel * 500, 100))
        award = random.choice(['empty', 'doubleMoney', 
                                random.choice(range(500, 5000, 50)), 'gem'])
        for piece in app.pieces:
            if not piece.collected:
                award = random.choice(['empty', 'doubleMoney', 
                    random.choice(range(500, 5000, 50)), 'gem', 'puzzle'])
    app.bonusItem.append(BonusItem(blood, btype, award))
    
def play_checkBonusState(app):
    for bonus in app.bonusItem[:1]:
        if bonus.blood <= 0:
            play_bonusAward(app, bonus)
            app.bonusItem.pop(0)
            
def play_checkEnemyAvaliability(app):
    for zombie in app.zombie:
        data = app.zombie[zombie]
        if ('Boss' in zombie and data['level'] <= app.experienceLevel 
            and zombie not in app.avaliableBoss):
              app.avaliableBoss.add(zombie)  
        elif ('Boss' not in zombie and data['level'] <= app.experienceLevel 
            and zombie not in app.avaliableZombie):
                app.avaliableZombie.add(zombie)
    
def play_checkMoneyBoostTimer(app):
    if app.moneyBoostTimer != None:
        if app.step % 30 == 0:
            app.moneyBoostTimer -= 1
        if app.step % 15 == 0:
            app.moneyCountDown -= 6
        if app.moneyBoostTimer <= 0:
            app.moneyIndex = 2
            app.moneyBoostTimer = None
            app.moneyCountDown = 360
    
def play_checkExperience(app):
    requiredUpgradeExperience = app.experienceLevel * 150
    if app.experience >= requiredUpgradeExperience:
        app.experience = 0
        app.money += min(requiredUpgradeExperience * 10, 10000)
        app.experienceLevel += 1
        app.awardMessage = 'LEVEL UP'
        app.awardMessageTimer = 1.5
        if app.soundEffect:
            app.levelUp.play()
        if app.experienceLevel % 5 == 0:
            app.wallBlood = min(app.wallBlood + app.experienceLevel * 100, app.wallBloodMax)

def play_checkGameOver(app):
    if app.wallBlood <= 0:
        app.gameOver = True
        app.wallBlood = app.wallBloodMax
        app.step = 1
        app.newRecord = app.experienceLevel > app.maxLevel
        app.maxLevel = app.experienceLevel
        app.gameOverTimer = 6 if app.newRecord else 5
        
def play_checkGameOverTimer(app):
    if app.gameOverTimer == None:
        return
    
    if app.gameOverTimer <= 0:
        app.gameOverTimer = None
        return

    if app.step % 30 == 0:
        app.gameOverTimer -= 1
        
    if ((app.newRecord and app.gameOverTimer == 6) 
            or (not app.newRecord and app.gameOverTimer == 5)):
        app.gameoverWordy += 1
        app.gameoverWordMultiplier += 0.1
    
    play_gameOverAnimation(app)
    
def play_gameOverAnimation(app):
    if app.step >= 30: app.showGem = True
    if app.step >= 45: app.showGemN = True
    if app.step >= 60: app.showPuzzle = True
    if app.step >= 75: app.showPuzzleN = True
    if app.newRecord:
        if app.step >= 90:
            app.showNewLevel = True
        if app.step >= 120:
            app.showRevive = True
        if app.step >= 150:
            app.showRestart = True
    else:
        if app.step >= 90:
            app.showRevive = True
        if app.step >= 120:
            app.showRestart = True

def play_checkBombExplode(app):
    if app.bombState == 'explode':
            app.bombr += app.bombRadius // 10
                
    if app.explodeTimer != None and app.explodeTimer <= 0:
        play_bombExplode(app)
        if app.soundEffect:
            app.explode.play()
        app.explodeTimer = None
        app.bombState = 'charging'
        app.bombr = 10
        
def play_checkBombAimTimer(app):
    if app.aimTimer != None and app.aimTimer <= 0:
        app.bombState = 'explode'
        app.bombx = app.aimx
        app.bomby = app.aimy
        app.aimTimer = None
        app.explodeTimer = 2
    if app.step % 30 == 0:
        if app.aimTimer != None:
            app.aimTimer -= 1
    
def play_checkZombieAttack(app):
    attackIndex = 0
    for enemy in app.attack:
        attackIndex += enemy.ATK
    if len(app.attack) > 0:
        app.wallBlood -= max(attackIndex // 10, 0.1)

def play_updateBullet(app):
    if app.ATK >= (app.bulletLevel + 1) * 10 and app.bulletLevel <6:
        app.bulletLevel += 1
        
def play_produceBullet(app):
    fireInterval = int(30 / app.bulletPerSecond)
    if app.bulletTimer >= fireInterval:
        for solider in app.solider: #produce bullet for each solider
            url = app.bulletType[app.bulletLevel]
            app.bullet.append(Bullet(solider.x, solider.y, url))
            app.bulletTimer = 0
            
def play_produceEnemy(app):
    ex = random.randint(190, 390)
    ey = random.randint(0, 30)
    if app.step % 30 == 0:
        attempt = 0
        app.bigMonsterExist = any(enemy.level > 5 for enemy in app.enemy)
        while not app.bigMonsterExist and attempt < 10:
            x = random.randint(230, 350)
            y = random.randint(-200, -150)
            if play_isLegalEnemy(app, x, y) and list(app.avaliableBoss) != []:
                boss = random.choice(list(app.avaliableBoss))
                app.enemy.append(Enemy(app, x, y, boss))
                app.bigMonsterExist = True
                break
            attempt += 1
    if play_isLegalEnemy(app, ex, ey) and len(app.enemy) < min(20*app.experienceLevel, 100):
        zombieList = list(app.avaliableZombie)
        zombie = random.choice(zombieList)
        app.enemy.append(Enemy(app, ex, ey, zombie))
            
def play_bulletMove(app):
    for bullet in app.bullet:
        Bullet.shooting(bullet, app)
        if bullet.y < 0:
            app.bullet.remove(bullet)
            continue
        play_checkShooting(app, bullet)

def play_enemyMove(app):
    for enemy in app.enemy:
        if enemy.y < 380 - enemy.r:
            Enemy.marching(enemy)
        else:
            enemy.mood = 'attacking'
    app.wallBeingAttacked = any(enemy.mood == 'attacking' for enemy in app.enemy)
        
def play_showWarningMessage(app):
    if app.warningMessageTimer <= 0:
            app.warningMessage = ''
            
    elif app.warningMessageTimer > 0:
        if app.step % 30 == 0:
            app.warningMessageTimer -= 1

def play_showAwardMessage(app):
    if app.awardMessageTimer <= 0:
            app.awardMessage = ''
    elif app.awardMessageTimer > 0:
        if app.step % 30 == 0:
            app.awardMessageTimer -= 1
    
def play_bonusAward(app, bonus):
    if bonus.award == 'solider':
        Solider.increaseSolider(app)
        return
    elif bonus.award == 'gun':
        n = random.choice([1, 2])
        L = [2] * 15 + [3] * 25 + [4] * 35 + [5] * 20 + [10] * 5
        add = random.choice(L)
        if n == 1: 
            app.ATK += add
            app.awardMessage = f'Bullet Damage + {add}'
            app.awardMessageTimer = 2
        elif n == 2: 
            if app.bulletPerSecond < 15:
                app.bulletPerSecond += 0.5
                app.awardMessage = f'Fire Rate + 0.5/s'
                app.awardMessageTimer = 2
            else:
                app.ATK += add
                app.awardMessage = f'Bullet Damage + {add}'
                app.awardMessageTimer = 2
    elif bonus.award == 'empty':
        app.awardMessage = 'Ah oh, this is an empty box'
        app.awardMessageTimer = 2
    elif bonus.award == 'doubleMoney':
        app.moneyIndex = random.randint(3, 10)
        app.awardMessage = f'30s Money Gain x{app.moneyIndex} !'
        app.moneyBoostTimer = 30
        app.awardMessageTimer = 2
    elif isinstance(bonus.award, int):
        app.awardMessage = f'You got money {bonus.award}'
        app.awardMessageTimer = 2
        app.money += bonus.award
    elif bonus.award == 'gem':
        n = random.randint(5, 100)
        app.awardMessage = f'You got {n} gem'
        app.awardMessageTimer = 2
        app.gemInsideGame += n
    elif bonus.award == 'puzzle':
        n = random.randint(5, 100)
        app.awardMessage = f'You got puzzle piece x1'
        app.awardMessageTimer = 2
        for piece in app.pieces:
            if not piece.collected:
                app.puzzleInsideGame.append(piece)
                piece.collected = True
                break

def play_isLegalEnemy(app, ex, ey):
    for enemy in app.enemy:
        if distance(enemy.x, enemy.y, ex, ey) <= enemy.r + 15:
            return False
    return True
    
def play_checkEnemyState(app):
    for enemy in app.enemy:
        if enemy.mood == 'attacking' and enemy not in app.attack:
            app.attack.append(enemy)
    
def play_checkShooting(app, bullet):
    for enemy in app.enemy:
        if distance(enemy.x, enemy.y, bullet.x, bullet.y) < enemy.r + 5:
            enemy.blood -= app.ATK
            if app.soundEffect:
                app.zombieHit.play()
            if enemy.blood <= 0:
                if enemy in app.attack:
                    app.attack.remove(enemy)
                    if len(app.attack) == 0:
                        app.wallBeingAttacked = False
                if enemy.level > 2:
                    app.bigMonsterExist = False
                app.experience += enemy.level
                app.money += enemy.level * app.moneyIndex 
                app.enemy.remove(enemy)
            try:
                app.bullet.remove(bullet)
            except:
                pass
    for bonus in app.bonusItem[:1]:
        if (bullet.y < bonus.y + bonus.height and 
            bonus.x <= bullet.x <= bonus.x + bonus.width):
            bonus.blood -= 1
            app.bullet.remove(bullet)
            if app.soundEffect:
                interval = int (bonus.maxBlood / 5)
                if bonus.bType == 'ice':
                    app.iceHit.play()
                    if bonus.blood % interval == 0 and bonus.blood > 5:
                        app.iceCrack.play()
                    if bonus.blood <= 0: app.iceBreak.play()
                if bonus.bType == 'box':
                    app.boxHit.play()
                    if bonus.blood % interval == 0 and bonus.blood > 5:
                        app.boxCrack.play()
                    if bonus.blood <= 0: app.boxBreak.play()
            if bonus.blood <= 0:
                play_bonusAward(app, bonus)
                app.bonusItem.pop(0)
                
def play_bombExplode(app):
    dead = [] # store dead enemy to prevent the code jump over adjacent enemy
    for enemy in app.enemy:
        if distance(enemy.x, enemy.y, app.bombx, app.bomby) <= app.bombr + enemy.r:
            enemy.blood -= app.bombHurt
            if enemy.blood <= 0:
                if enemy in app.attack:
                    app.attack.remove(enemy)
                    if len(app.attack) == 0:
                        app.wallBeingAttacked = False
                if enemy.level > 2:
                    app.bigMonsterExist = False
                app.experience += enemy.level
                app.money += enemy.level * 2
                dead.append(enemy)
    for enemy in dead:
        app.enemy.remove(enemy)

