    piece = app.selectedPiece
    if app.selectedPiece == None or piece.correctPosition:
        return
    piece = app.selectedPiece
    piece.current = PuzzlePiece.getNewPosition(piece, mouseX, mouseY)
    x0, y0 = piece.current[0]
    x1, y1 = piece.correct[0]
    if distance(x0, y0, x1, y1) <= app.snapDistance:
        piece.current = piece.correct
        piece.correctPosition = True
