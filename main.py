def repositArrow(arrow, dx, dy):
    xL = []
    yL = []
    for i in range(len(arrow)):
        if i % 2 == 0:
            xL.append(arrow[i])
        else:
            yL.append(arrow[i])
    newx = []
    newy = []
    for x in xL:
        newx.append(x + dx)
    for y in yL:
        newy.append(y + dy)
    res = []
    for x, y in zip(newx, newy):
        res.extend([x, y])
    return res
    
def distance(x0, y0, x1, y1):
    return ((x0 - x1) ** 2 + (y0-y1) ** 2) ** 0.5
    
def drawPrettyRect(left, top, width, height, r, fill):
    drawCircle(left, top, r, fill = fill) #left top
    drawCircle(left, top + height, r, fill = fill) # left buttom
    drawCircle(left + width, top, r, fill = fill) # right top
    drawCircle(left + width, top + height, r, fill = fill) # right buttom
    drawRect(left - r, top, 2*r, height, fill = fill) #vertical left
    drawRect(left + width - r, top, 2*r, height, fill = fill) # vertical right
    drawRect(left, top - r, width, 2*r, fill = fill) # horizontal top
    drawRect(left, top + height - r, width, 2*r, fill = fill) # horizontal buttom
    drawRect(left, top, width, height, fill = fill)
    
