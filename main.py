def game_getShortestPathEasy(app, path, visited, x, y):
    if x == 0 or x == app.rows - 1 or y == 0 or y == app.cols - 1:
        return path
        
    else:
        visited.add((x, y))
        for dx, dy in [(-1, 0), (1, 0), (0, 1), (0, -1)]:
            row, col = x + dx, y + dy
            if (row, col) not in visited and isLegalMove(app, row, col):
                newpath = path + [(row, col)]
                solution = game_getShortestPathEasy(app, newpath, visited, row, col)
                if solution != None:
                    return solution
        visited.remove((x, y))
        return None
        
