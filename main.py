def game_getShortestPathHard(app, x, y):
    if x == 0 or x == app.rows - 1 or y == 0 or y == app.cols - 1:
        return []
        
    else:
        queue = [(x, y, [])]
        visited = set()
        visited.add((x,y))
        while len(queue) > 0:
            x, y, path = queue.pop(0)
            for dx, dy in [(-1, 0), (1, 0), (0, 1), (0, -1)]:
                row, col = x + dx, y + dy
                if ((row == 0 or row == app.rows - 1 
                    or col == 0 or col == app.cols - 1) and 
                    (row, col) not in visited 
                    and isLegalMove(app, row, col)):
                    return path + [(row, col)]
                    
                if (row, col) not in visited and isLegalMove(app, row, col):
                    visited.add((row, col))
                    newPath = path + [(row, col)]
                    queue.append((row, col, newPath))
        return None
        
