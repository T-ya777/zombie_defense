class PuzzlePiece:
    def __init__(self, setID, ID, correct, inventory, offset):
        self.setID = setID
        self.ID = ID
        self.correct = correct
        self.inventory = inventory
        self.current = self.inventory
        self.collected = False
        self.correctPosition = False
        baseURL = f'https://raw.githubusercontent.com/T-ya777/112FinalProjectSource/master/puzzle{setID}'
        self.url = f'{baseURL}/{ID}.png'
        self.offset = offset
        self.multiplier = 0.15
        
    def listCordinate(self):
        M = []
        for x, y in self.current:
            M.extend([x, y])
        return M
        
    def getCenter(self):
        xL = []
        yL = []
        for x, y in self.current:
            xL.append(x)
            yL.append(y)
        xAvg = sum(xL) / len(xL)
        yAvg = sum(yL) / len(yL)
        return xAvg, yAvg
        
    def resize(self):
        pieceWidth, pieceHeight = getImageSize(self.url)
        return pieceWidth * self.multiplier, pieceHeight * self.multiplier
    
    #learnt and used calculation from:
    # https://www.youtube.com/watch?v=RSXM9bgqxJM
    def isInside(self, x, y):
        cutPoint = 0
        length = len(self.current)
        edges = [(self.current[0], self.current[length - 1])]
        for i in range(length - 1):
            j = i + 1
            edges.append(((self.current[i], self.current[j])))
        for edge in edges:
            (x1, y1), (x2, y2) = edge
            maxy = max(y1, y2)
            miny = min(y1, y2)
            if (miny < y < maxy and 
                x < x1 + ((y-y1)/(y2-y1)) * (x2 - x1)):
                    cutPoint += 1
        return cutPoint % 2 == 1
        
    def getNewPosition(self, x0, y0):
        cx, cy = PuzzlePiece.getCenter(self)
        dxL = []
        dyL = []
        for x, y in self.current:
            dxL.append(x - cx)
            dyL.append(y - cy)
        L = PuzzlePiece.interLeave(dxL.copy(), dyL.copy())
        new = []
        for dx, dy in L:
            new.append((dx + x0, dy + y0))
        return new
        
    def checkPosition(self, app):
        cx, cy = PuzzlePiece.getCenter(self)
        if cy <= 455:
            self.multiplier = app.correctMultiplier
            self.current = self.correct
        else:
            self.multiplier = app.inventoryMultiplier
            self.current = self.inventory
        PuzzlePiece.resize(self)
        
    def checkOutOfBound(self):
        xL = []
        yL = []
        for x, y in self.current:
            xL.append(x)
            yL.append(y)
        left = min(xL)
        right = max(xL)
        top = min(yL)
        buttom = max(yL)
        return left <55 or right > 348 or top < 62 or buttom > 455
    
    @staticmethod
    def interLeave(L, M):
        if L == []:
            return []
        else:
            res = [(L[0], M[0])]
            return res + PuzzlePiece.interLeave(L[1:], M[1:])

