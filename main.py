class Bullet:
    def __init__(self, x, y, url):
        self.x = x
        self.y = y
        self.url = url
        
    def shooting(self, app):
        self.y -= app.bulletSpeed
        
    def resize(self):
        width, height = getImageSize(self.url)
        multiplier = min(width/14, height/28)
        w, h = width/multiplier, height/multiplier
        return w, h
        
class Solider:
    def __init__(self, x, y, r):
        self.x = x
        self.y = y
        self.r = r
        
    def increaseSolider(app):
        if len(app.solider) < 7:
            lastSolider  = app.solider[-1]
            firstSolider  = app.solider[0]
        if len(app.solider) == 3 or len(app.solider) == 7:
            x = firstSolider.x + firstSolider.r * 2
            y = firstSolider.y + firstSolider.r * 2
            r = lastSolider.r
        else:
            x = lastSolider.x - 4 * lastSolider.r
            y = lastSolider.y
            r = lastSolider.r
        app.solider.append(Solider(x, y, r))
        
