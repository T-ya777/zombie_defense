def getCell(app, x, y):
    dx = x - app.boardLeft 
    dy = y - app.boardTop         
    cellWidth, cellHeight = getCellSize(app)
    row = math.floor(dy / cellHeight)
    col = math.floor(dx / cellWidth)
    if (0 <= row < app.rows) and (0 <= col < app.cols):
        return (row, col)
    else:
        return None
        
def game_zombieMove(app):
    if app.zombieMood == 'Easy':
        path = game_getShortestPathEasy(app, [], set(), app.zx, app.zy)
    elif app.zombieMood == 'Medium':
        path = game_getShortestPathMedium(app, [], set(), app.zx, app.zy, None)
        app.step = 0
        app.startTiming = True
    elif app.zombieMood == 'Hard':
        path = game_getShortestPathHard(app, app.zx, app.zy)

    if path == None or len(path) == 0:
        if (app.zx == 0 or app.zx == app.rows - 1 or app.zy == 0 
                or app.zy == app.cols - 1):
            app.lose = True
        else:
            app.win = True
            app.gem += app.gemGain
        return

    nextStep = path[0]
