class Enemy:
    def __init__(self, app, x, y, type):
        self.x = x
        self.y = y
        self.mood = 'marching'
        self.type = type
        
        config = app.zombie[type]
        levelMultiplier = app.experienceLevel // 10 + 0.5
        if app.experienceLevel < 10:
            levelMultiplier = 1
        self.r = config['r']
        self.ATK = config['ATK'] * levelMultiplier
        self.blood = config['blood'] * levelMultiplier
        self.maxBlood = self.blood
        self.speed = config['speed'] * levelMultiplier
        self.url = config['url']
        self.level = config['level']
        
    def __repr__(self):
        return self.x, self.y
        
    def marching(self):
        self.y += self.speed
        
    def resize(self):
        width, height = getImageSize(self.url)
        if "Boss" in self.type:
            multiplier = min(width/(self.r * 5), height/(self.r * 5))
        else:
            multiplier = min(width/(self.r * 7), height/(self.r * 7))
        w, h = width/multiplier, height/multiplier
        return w, h

